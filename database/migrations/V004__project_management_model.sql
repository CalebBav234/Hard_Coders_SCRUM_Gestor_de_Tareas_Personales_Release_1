-- PROJECT ||--|{ PROJECT_PLAN_HISTORY, TASK ||--|{ TASK_PLAN_HISTORY y
-- TASK ||..|{ TASK_STATUS_HISTORY: la revisión/estado inicial debe insertarse en la
-- MISMA transacción que el proyecto o la tarea. Se valida al hacer COMMIT.

CREATE OR REPLACE FUNCTION task_manager.ensure_project_has_plan_history()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = task_manager, pg_temp
AS $function$
BEGIN
    IF EXISTS (SELECT 1 FROM task_manager.project WHERE project_id = NEW.project_id)
       AND NOT EXISTS (
           SELECT 1 FROM task_manager.project_plan_history WHERE project_id = NEW.project_id
       ) THEN
        RAISE EXCEPTION 'El proyecto % necesita al menos una revisión en project_plan_history',
            NEW.project_id
            USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END;
$function$;

CREATE OR REPLACE FUNCTION task_manager.ensure_task_has_histories()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = task_manager, pg_temp
AS $function$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM task_manager.task WHERE task_id = NEW.task_id) THEN
        RETURN NULL;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM task_manager.task_plan_history WHERE task_id = NEW.task_id) THEN
        RAISE EXCEPTION 'La tarea % necesita al menos una revisión en task_plan_history',
            NEW.task_id
            USING ERRCODE = '23514';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM task_manager.task_status_history WHERE task_id = NEW.task_id) THEN
        RAISE EXCEPTION 'La tarea % necesita al menos un registro en task_status_history',
            NEW.task_id
            USING ERRCODE = '23514';
    END IF;

    RETURN NULL;
END;
$function$;

