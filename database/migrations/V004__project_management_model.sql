-- V004: modelo de gestión de proyectos (diagrama ER V4 / UML "Gestor de Proyectos").
--
-- Jerarquía: proyecto -> etapa -> actividad -> tarea -> subtarea, con usuarios,
-- asignaciones, catálogos de estado/prioridad, historiales de plan y de estado,
-- y cotizaciones de tipo de cambio. Moneda fija BOB; tiempos en minutos.
--
-- Estrategia:
--   1. Las tablas del modelo anterior (V001-V003) se archivan intactas en el
--      esquema task_manager_legacy (sin permisos para la aplicación). No se pierde
--      ningún dato; cuando el equipo lo decida basta con:
--          DROP SCHEMA task_manager_legacy CASCADE;
--   2. Se crea el modelo nuevo en task_manager.
--   3. Si existían tareas, se trasladan a un "Proyecto legado":
--        categoría       -> actividad (más "Sin categoría")
--        tarea raíz      -> task       (conserva el id)
--        tarea hija      -> subtask de su tarea raíz (conserva el id)
--        INACTIVA/ACTIVA/TERMINADA -> PENDIENTE/EN_PROGRESO/COMPLETADA
--        borrado lógico  -> CANCELADA
--        segundos activos -> actual_duration_minutes (redondeo hacia arriba)
--
-- Este archivo es inmutable después de aplicarse en un entorno compartido.
-- Debe ejecutarse en una única transacción (migrate.ps1 usa --single-transaction).

-------------------------------------------------------------------------------
