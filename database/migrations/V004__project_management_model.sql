DO $revoke_legacy$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'gestor_tareas_app') THEN
        EXECUTE 'REVOKE ALL ON ALL TABLES IN SCHEMA task_manager_legacy FROM gestor_tareas_app';
        EXECUTE 'REVOKE ALL ON ALL SEQUENCES IN SCHEMA task_manager_legacy FROM gestor_tareas_app';
    END IF;
END;
$revoke_legacy$;

