DO $grant_permissions$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'gestor_tareas_app') THEN
        -- V002 define privilegios por defecto (SELECT, INSERT, UPDATE) para tablas
        -- nuevas; se revocan para conceder exactamente lo necesario.
        EXECUTE 'REVOKE ALL ON ALL TABLES IN SCHEMA task_manager FROM gestor_tareas_app';
        EXECUTE 'GRANT USAGE ON SCHEMA task_manager TO gestor_tareas_app';
        EXECUTE 'GRANT SELECT ON public.database_schema_migrations TO gestor_tareas_app';

        -- Catálogos administrados por migraciones.
        EXECUTE 'GRANT SELECT ON task_manager.project_status, task_manager.work_status, '
             || 'task_manager.task_priority, task_manager.exchange_rate_source '
             || 'TO gestor_tareas_app';

        -- Usuarios: se desactivan (is_active), no se borran.
        EXECUTE 'GRANT SELECT, INSERT, UPDATE ON task_manager.app_user TO gestor_tareas_app';

        -- Jerarquía de trabajo y asignaciones.
        EXECUTE 'GRANT SELECT, INSERT, UPDATE, DELETE '
             || 'ON task_manager.project, task_manager.stage, task_manager.activity, '
             || 'task_manager.task, task_manager.subtask, task_manager.task_assignment '
             || 'TO gestor_tareas_app';

        -- Historiales y cotizaciones: solo se agregan filas.
        EXECUTE 'GRANT SELECT, INSERT '
             || 'ON task_manager.project_plan_history, task_manager.task_plan_history, '
             || 'task_manager.task_status_history, task_manager.exchange_rate_quote '
             || 'TO gestor_tareas_app';

        EXECUTE 'GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA task_manager '
             || 'TO gestor_tareas_app';
    END IF;
END;
$grant_permissions$;
