DO $migrate_legacy$
DECLARE
    v_system_user_id    integer;
    v_project_id        integer;
    v_stage_id          integer;
    v_started_at        timestamptz;
    v_pending_id        integer;
    v_in_progress_id    integer;
    v_completed_id      integer;
    v_cancelled_id      integer;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM task_manager_legacy.tasks) THEN
        RETURN;
    END IF;

    SELECT work_status_id INTO v_pending_id     FROM task_manager.work_status WHERE name = 'PENDIENTE';
    SELECT work_status_id INTO v_in_progress_id FROM task_manager.work_status WHERE name = 'EN_PROGRESO';
    SELECT work_status_id INTO v_completed_id   FROM task_manager.work_status WHERE name = 'COMPLETADA';
    SELECT work_status_id INTO v_cancelled_id   FROM task_manager.work_status WHERE name = 'CANCELADA';

    SELECT min(created_at) INTO v_started_at FROM task_manager_legacy.tasks;

    -- Usuario técnico: inactivo y con un hash inválido, no puede iniciar sesión.
    INSERT INTO task_manager.app_user
        (email, password_hash, given_names, family_names, is_chief, is_active, created_at, updated_at)
    VALUES
        ('migracion.v004@gestor-tareas.local', '!', 'Sistema', 'Migración V004', true, false,
         v_started_at, v_started_at)
    RETURNING user_id INTO v_system_user_id;

    INSERT INTO task_manager.project
        (name, description, manager_user_id, project_status_id, created_by_user_id, created_at, updated_at)
    VALUES
        ('Proyecto legado',
         'Tareas migradas desde el gestor de tareas personales (V001-V003).',
         v_system_user_id,
         (SELECT project_status_id FROM task_manager.project_status WHERE name = 'EN_EJECUCION'),
         v_system_user_id, v_started_at, v_started_at)
    RETURNING project_id INTO v_project_id;

    INSERT INTO task_manager.project_plan_history
        (project_id, revision_number, budget_bob, estimated_duration_minutes,
         changed_at, changed_by_user_id, reason)
    VALUES
        (v_project_id, 1, 0.00, 0, v_started_at, v_system_user_id,
         'Plan inicial generado por la migración V004');

    INSERT INTO task_manager.stage
        (project_id, name, description, work_status_id, created_at, updated_at)
    VALUES
        (v_project_id, 'Etapa legado', 'Etapa única para las tareas migradas.',
         v_in_progress_id, v_started_at, v_started_at)
    RETURNING stage_id INTO v_stage_id;

    -- Cada tarea legado apunta a su raíz (las jerarquías profundas se aplanan).
    CREATE TEMP TABLE tmp_legacy_task_root ON COMMIT DROP AS
    WITH RECURSIVE tree AS (
        SELECT id, id AS root_id
        FROM task_manager_legacy.tasks
        WHERE parent_task_id IS NULL
        UNION ALL
        SELECT child.id, tree.root_id
        FROM task_manager_legacy.tasks AS child
        JOIN tree ON child.parent_task_id = tree.id
    )
    SELECT id, root_id FROM tree;

    -- Categoría -> actividad (categorías vigentes y las usadas por tareas raíz).
    CREATE TEMP TABLE tmp_legacy_activity (
        category_id bigint,
        activity_id integer NOT NULL
    ) ON COMMIT DROP;

    WITH source_categories AS (
        SELECT category.id, category.name, category.created_at, category.updated_at
        FROM task_manager_legacy.categories AS category
        WHERE category.deleted_at IS NULL
           OR EXISTS (
               SELECT 1 FROM task_manager_legacy.tasks AS task
               WHERE task.category_id = category.id AND task.parent_task_id IS NULL
           )
    ),
    inserted AS (
        INSERT INTO task_manager.activity (stage_id, name, description, work_status_id, created_at, updated_at)
        SELECT v_stage_id, name, 'Categoría migrada #' || id, v_in_progress_id, created_at, updated_at
        FROM source_categories
        ORDER BY id
        RETURNING activity_id, description
    )
    INSERT INTO tmp_legacy_activity (category_id, activity_id)
    SELECT substring(description FROM '#(\d+)$')::bigint, activity_id
    FROM inserted;

    UPDATE task_manager.activity AS activity
    SET description = 'Categoría migrada desde el modelo anterior.'
    FROM tmp_legacy_activity AS map
    WHERE map.activity_id = activity.activity_id;

    IF EXISTS (
        SELECT 1 FROM task_manager_legacy.tasks
        WHERE parent_task_id IS NULL
          AND (category_id IS NULL
               OR category_id NOT IN (SELECT category_id FROM tmp_legacy_activity))
    ) THEN
        WITH inserted AS (
            INSERT INTO task_manager.activity (stage_id, name, description, work_status_id, created_at, updated_at)
            VALUES (v_stage_id, 'Sin categoría', 'Tareas sin categoría en el modelo anterior.',
                    v_in_progress_id, v_started_at, v_started_at)
            RETURNING activity_id
        )
        INSERT INTO tmp_legacy_activity (category_id, activity_id)
        SELECT NULL, activity_id FROM inserted;
    END IF;

    -- Tareas raíz -> task (conservan su id).
    INSERT INTO task_manager.task (
        task_id, activity_id, title, description, work_status_id, task_priority_id,
        allocated_budget_bob, estimated_duration_minutes, actual_duration_minutes,
        completed_at, completed_by_user_id, created_at, updated_at
    )
    OVERRIDING SYSTEM VALUE
    SELECT
        legacy.id::integer,
        COALESCE(
            (SELECT map.activity_id FROM tmp_legacy_activity AS map WHERE map.category_id = legacy.category_id),
            (SELECT map.activity_id FROM tmp_legacy_activity AS map WHERE map.category_id IS NULL)
        ),
        legacy.title,
        left(legacy.description, 2000),
        CASE
            WHEN legacy.deleted_at IS NOT NULL THEN v_cancelled_id
            WHEN legacy.status = 'TERMINADA' THEN v_completed_id
            WHEN legacy.status = 'ACTIVA' THEN v_in_progress_id
            ELSE v_pending_id
        END,
        (SELECT task_priority_id FROM task_manager.task_priority WHERE name = legacy.priority),
        0.00,
        0,
        CASE WHEN seconds.effective > 0 THEN ceil(seconds.effective / 60.0)::integer END,
        CASE WHEN legacy.deleted_at IS NULL AND legacy.status = 'TERMINADA' THEN legacy.completed_at END,
        CASE WHEN legacy.deleted_at IS NULL AND legacy.status = 'TERMINADA' THEN v_system_user_id END,
        legacy.created_at,
        legacy.updated_at
    FROM task_manager_legacy.tasks AS legacy
    CROSS JOIN LATERAL (
        SELECT legacy.total_active_seconds
            + CASE
                WHEN legacy.status = 'ACTIVA' AND legacy.activated_at IS NOT NULL
                    THEN floor(EXTRACT(epoch FROM (
                        COALESCE(legacy.deleted_at, CURRENT_TIMESTAMP) - legacy.activated_at
                    )))::bigint
                ELSE 0
              END AS effective
    ) AS seconds
    WHERE legacy.parent_task_id IS NULL;

    -- Tareas hijas -> subtask de su raíz (conservan su id).
    INSERT INTO task_manager.subtask (
        subtask_id, task_id, title, description, work_status_id,
        completed_at, completed_by_user_id, created_at, updated_at
    )
    OVERRIDING SYSTEM VALUE
    SELECT
        legacy.id::integer,
        root.root_id::integer,
        legacy.title,
        left(legacy.description, 2000),
        CASE
            WHEN legacy.deleted_at IS NOT NULL THEN v_cancelled_id
            WHEN legacy.status = 'TERMINADA' THEN v_completed_id
            WHEN legacy.status = 'ACTIVA' THEN v_in_progress_id
            ELSE v_pending_id
        END,
        CASE WHEN legacy.deleted_at IS NULL AND legacy.status = 'TERMINADA' THEN legacy.completed_at END,
        CASE WHEN legacy.deleted_at IS NULL AND legacy.status = 'TERMINADA' THEN v_system_user_id END,
        legacy.created_at,
        legacy.updated_at
    FROM task_manager_legacy.tasks AS legacy
    JOIN tmp_legacy_task_root AS root ON root.id = legacy.id
    WHERE legacy.parent_task_id IS NOT NULL;

    -- Revisión inicial del plan de cada tarea.
    INSERT INTO task_manager.task_plan_history
        (task_id, revision_number, allocated_budget_bob, estimated_duration_minutes,
         changed_at, changed_by_user_id, reason)
    SELECT task_id, 1, allocated_budget_bob, estimated_duration_minutes,
           created_at, v_system_user_id, 'Plan inicial generado por la migración V004'
    FROM task_manager.task;

    -- Historial de estados de las tareas raíz.
    INSERT INTO task_manager.task_status_history
        (task_id, previous_status_id, new_status_id, changed_at, changed_by_user_id, reason)
    SELECT
        history.task_id::integer,
        CASE history.from_status
            WHEN 'INACTIVA' THEN v_pending_id
            WHEN 'ACTIVA' THEN v_in_progress_id
            WHEN 'TERMINADA' THEN v_completed_id
        END,
        CASE history.to_status
            WHEN 'INACTIVA' THEN v_pending_id
            WHEN 'ACTIVA' THEN v_in_progress_id
            WHEN 'TERMINADA' THEN v_completed_id
        END,
        history.changed_at,
        v_system_user_id,
        COALESCE(NULLIF(btrim(history.change_reason), ''), 'Migrado desde el historial V001-V003')
    FROM task_manager_legacy.task_status_history AS history
    JOIN task_manager.task AS task ON task.task_id = history.task_id
    ORDER BY history.changed_at, history.id;

    -- Tareas sin historial previo: registrar el estado actual.
    INSERT INTO task_manager.task_status_history
        (task_id, previous_status_id, new_status_id, changed_at, changed_by_user_id, reason)
    SELECT task.task_id, NULL,
           CASE legacy.status
               WHEN 'TERMINADA' THEN v_completed_id
               WHEN 'ACTIVA' THEN v_in_progress_id
               ELSE v_pending_id
           END,
           task.created_at, v_system_user_id, 'Estado registrado por la migración V004'
    FROM task_manager.task AS task
    JOIN task_manager_legacy.tasks AS legacy ON legacy.id = task.task_id
    WHERE NOT EXISTS (
        SELECT 1 FROM task_manager.task_status_history AS history
        WHERE history.task_id = task.task_id
    );

    -- Borrado lógico -> transición final a CANCELADA.
    INSERT INTO task_manager.task_status_history
        (task_id, previous_status_id, new_status_id, changed_at, changed_by_user_id, reason)
    SELECT task.task_id,
           CASE legacy.status
               WHEN 'TERMINADA' THEN v_completed_id
               WHEN 'ACTIVA' THEN v_in_progress_id
               ELSE v_pending_id
           END,
           v_cancelled_id, legacy.deleted_at, v_system_user_id,
           'Tarea eliminada lógicamente en el modelo anterior'
    FROM task_manager.task AS task
    JOIN task_manager_legacy.tasks AS legacy ON legacy.id = task.task_id
    WHERE legacy.deleted_at IS NOT NULL;

    PERFORM setval(pg_get_serial_sequence('task_manager.task', 'task_id'),
                   (SELECT max(task_id) FROM task_manager.task), true)
    WHERE EXISTS (SELECT 1 FROM task_manager.task);
    PERFORM setval(pg_get_serial_sequence('task_manager.subtask', 'subtask_id'),
                   (SELECT max(subtask_id) FROM task_manager.subtask), true)
    WHERE EXISTS (SELECT 1 FROM task_manager.subtask);
END;
$migrate_legacy$;

